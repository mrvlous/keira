/// Draws an 8x16 ASCII character onto the framebuffer at `(x, y)` pixel coordinates.
///
/// # Safety
///
/// Direct memory access to write pixels into the active framebuffer.
pub unsafe fn draw_char(x: u32, y: u32, c: char, fg: u32, bg: u32) {
    let ascii = c as usize;
    if !(32..=126).contains(&ascii) {
        return;
    }
    let font_idx = ascii - 32;
    let glyph = FONT_8X16[font_idx];

    for row in 0..16 {
        let bitmask = glyph[row];
        for col in 0..8 {
            if (bitmask & (1 << (7 - col))) != 0 {
                draw_pixel(x + col, y + (row as u32), fg);
            } else if bg != 0xFF000000 {
                draw_pixel(x + col, y + (row as u32), bg);
            }
        }
    }
}

/// Draws a text string onto the framebuffer starting at `(x, y)` pixel coordinates.
///
/// # Safety
///
/// Direct memory access to write pixels into the active framebuffer.
pub unsafe fn draw_string(x: u32, y: u32, text: &str, fg: u32, bg: u32) {
    let mut cur_x = x;
    for c in text.chars() {
        if c == '\n' {
            cur_x = x;
            continue;
        }
        draw_char(cur_x, y, c, fg, bg);
        cur_x += 8;
    }
}
