//! Unit tests for X25519 scalar multiplication and Diffie-Hellman key exchange.

use super::*;

#[test]
fn test_x25519_key_exchange_vectors() {
    let alice_priv: [u8; 32] = [
        0x77, 0x07, 0x6d, 0x0a, 0x73, 0x18, 0xa5, 0x7d, 0x3c, 0x16, 0xc1, 0x72, 0x51, 0x52, 0x53,
        0x02, 0xf5, 0x0e, 0xc3, 0x4d, 0x03, 0xf8, 0xa7, 0x28, 0x36, 0x5b, 0x6f, 0x44, 0xd2, 0x36,
        0x01, 0x4e,
    ];
    let expected_alice_pub: [u8; 32] = [
        0x0b, 0xce, 0x39, 0x0c, 0xe5, 0x3e, 0x5b, 0xde, 0x17, 0xf4, 0xed, 0x48, 0x69, 0x52, 0x0e,
        0x19, 0x01, 0x41, 0xe1, 0xe7, 0x31, 0x68, 0x36, 0x86, 0x0f, 0x0f, 0xdc, 0x12, 0x82, 0xaf,
        0xdd, 0x54,
    ];

    let bob_priv: [u8; 32] = [
        0x5d, 0xab, 0x08, 0x7e, 0x62, 0x4a, 0x8a, 0x4b, 0x79, 0xe1, 0x7f, 0x8b, 0x83, 0x80, 0x0e,
        0xe6, 0x6f, 0x3b, 0xb1, 0x29, 0x26, 0x18, 0xb6, 0xfd, 0x1c, 0x2f, 0x8b, 0x27, 0xff, 0x88,
        0xe0, 0xeb,
    ];
    let expected_bob_pub: [u8; 32] = [
        0xde, 0x9e, 0xdb, 0x7d, 0x7b, 0x7d, 0xc1, 0xb4, 0xd3, 0x5b, 0x61, 0xc2, 0xec, 0xe4, 0x35,
        0x37, 0x3f, 0x83, 0x43, 0xc8, 0x5b, 0x78, 0x67, 0x4d, 0xad, 0xfc, 0x7e, 0x14, 0x6f, 0x88,
        0x2b, 0x4f,
    ];

    let alice_pub = x25519(&alice_priv, &X25519_BASEPOINT);
    assert_eq!(alice_pub, expected_alice_pub);

    let bob_pub = x25519(&bob_priv, &X25519_BASEPOINT);
    assert_eq!(bob_pub, expected_bob_pub);

    let shared_alice = x25519(&alice_priv, &bob_pub);
    let shared_bob = x25519(&bob_priv, &alice_pub);

    assert_eq!(shared_alice, shared_bob);
    let expected_shared: [u8; 32] = [
        0x0d, 0xcd, 0x59, 0x36, 0xbc, 0xd6, 0x2f, 0x03, 0x4d, 0xe4, 0xf0, 0x5e, 0x13, 0x97, 0xb3,
        0x4e, 0x42, 0x4e, 0x35, 0x95, 0xc8, 0x1c, 0xf7, 0x29, 0xf8, 0x2f, 0x9a, 0xa7, 0x53, 0x3a,
        0x32, 0x5b,
    ];
    assert_eq!(shared_alice, expected_shared);
}
