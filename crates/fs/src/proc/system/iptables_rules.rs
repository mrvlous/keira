//! Dynamic `/proc/net/iptables` node reporting active Netfilter rule chains.

use crate::proc::system::hooks::NET_IPTABLES_HOOK;
use crate::proc::writer::BufWriter;
use core::fmt::Write;

/// Reads formatted Netfilter rule tables in canonical iptables-save format.
pub fn read_ip_tables_rules(buf: &mut [u8]) -> Result<usize, &'static str> {
    if let Some(hook) = unsafe { NET_IPTABLES_HOOK } {
        return Ok(hook(buf));
    }

    let mut writer = BufWriter::new(buf);

    let _ = writeln!(writer, "# Generated by Keira Netfilter Subsystem");
    let _ = writeln!(writer, "*filter");
    let _ = writeln!(writer, ":INPUT ACCEPT [0:0]");
    let _ = writeln!(writer, ":FORWARD ACCEPT [0:0]");
    let _ = writeln!(writer, ":OUTPUT ACCEPT [0:0]");
    let _ = writeln!(writer, "COMMIT");

    Ok(writer.len())
}
