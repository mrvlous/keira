//! Live in-kernel Netfilter rules and conntrack telemetry formatting.

use core::fmt::Write;

use crate::filter::firewall::engine::{
    CONNTRACK_TABLE, PACKETS_DROPPED, PACKETS_INSPECTED, RULE_TABLE,
};

/// Fixed-capacity slice writer implementing `core::fmt::Write`.
struct SliceWriter<'a> {
    buf: &'a mut [u8],
    offset: usize,
}

impl<'a> SliceWriter<'a> {
    fn new(buf: &'a mut [u8]) -> Self {
        Self { buf, offset: 0 }
    }

    fn len(&self) -> usize {
        self.offset
    }
}

impl<'a> Write for SliceWriter<'a> {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        let bytes = s.as_bytes();
        let remaining = self.buf.len().saturating_sub(self.offset);
        let to_copy = remaining.min(bytes.len());
        self.buf[self.offset..self.offset + to_copy].copy_from_slice(&bytes[..to_copy]);
        self.offset += to_copy;
        Ok(())
    }
}

/// Formats the live in-kernel Netfilter rule table into canonical `iptables-save` syntax.
pub fn format_iptables_rules(buf: &mut [u8]) -> usize {
    let mut writer = SliceWriter::new(buf);

    let _ = writeln!(writer, "# Generated by Keira Netfilter Subsystem");
    let _ = writeln!(writer, "*filter");
    let _ = writeln!(writer, ":INPUT ACCEPT [0:0]");
    let _ = writeln!(writer, ":FORWARD ACCEPT [0:0]");
    let _ = writeln!(writer, ":OUTPUT ACCEPT [0:0]");

    unsafe {
        for rule in RULE_TABLE.iter() {
            if !rule.in_use {
                continue;
            }
            let chain = core::str::from_utf8(&rule.chain)
                .unwrap_or("")
                .trim_matches('\0');
            let proto = core::str::from_utf8(&rule.proto)
                .unwrap_or("")
                .trim_matches('\0');
            let src = core::str::from_utf8(&rule.src_ip)
                .unwrap_or("")
                .trim_matches('\0');
            let dst = core::str::from_utf8(&rule.dst_ip)
                .unwrap_or("")
                .trim_matches('\0');
            let action = core::str::from_utf8(&rule.action)
                .unwrap_or("")
                .trim_matches('\0');

            if rule.dport > 0 {
                let _ = writeln!(
                    writer,
                    "-A {} -p {} -s {} -d {} --dport {} -j {} -c {}",
                    chain, proto, src, dst, rule.dport, action, rule.match_count
                );
            } else {
                let _ = writeln!(
                    writer,
                    "-A {} -p {} -s {} -d {} -j {} -c {}",
                    chain, proto, src, dst, action, rule.match_count
                );
            }
        }
    }

    let _ = writeln!(writer, "COMMIT");
    writer.len()
}

/// Formats the live in-kernel Netfilter connection tracking statistics.
pub fn format_conntrack_stat(buf: &mut [u8]) -> usize {
    let mut writer = SliceWriter::new(buf);

    let _ = writeln!(
        writer,
        "entries  searched     found       new   invalid    ignore    delete delete_list    insert insert_failed      drop early_drop     error search_restart"
    );

    unsafe {
        let in_use_count = CONNTRACK_TABLE.iter().filter(|c| c.in_use).count();
        let _ = writeln!(
            writer,
            "{:>7} {:>9} {:>9} {:>9} {:>9} {:>9} {:>9} {:>11} {:>9} {:>13} {:>9} {:>10} {:>9} {:>14}",
            in_use_count,
            PACKETS_INSPECTED,
            PACKETS_INSPECTED.saturating_sub(PACKETS_DROPPED),
            in_use_count,
            0,
            0,
            0,
            0,
            in_use_count,
            0,
            PACKETS_DROPPED,
            0,
            0,
            0
        );
    }

    writer.len()
}
